def view_bookings():
    if len(bookings) == 0:
        print("No bookings found.")
        return

    print("\nBOOKING HISTORY")
    for number, b in enumerate(bookings, start=1):
        route = find_route(b["route_id"])
        journey = route["departure_city"] + " -> " + route["destination_city"]
        print(f"{number}. {b['booking_id']} | {b['passenger_name']} | "
              f"{b['route_id']} ({journey}) | Seats: {b['seats']} | "
              f"Fare: Rs. {b['total_fare']} | {b['status']}")


# STEP 8: CANCEL A BOOKING (Feature 7)
def cancel_booking():
    booking_id = input("Enter booking ID to cancel: ").strip().upper()

    for booking in bookings:
        if booking["booking_id"] == booking_id:
            if booking["status"] != "Confirmed":
                print(f"Booking {booking_id} is already cancelled.")
            else:
                route = find_route(booking["route_id"])
                route["available_seats"] += booking["seats"]
                booking["status"] = "Cancelled"
                print(f"Booking {booking_id} has been cancelled.")
                print(f"Seats restored: {booking['seats']}")
                print(f"Route {route['route_id']} available seats: "
                      f"{route['available_seats']}")
            break
    else:
        print("Booking ID not found.")


