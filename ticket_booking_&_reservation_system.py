def view_availability():
    only_available = input("Show only routes with seats? (y/n): ").strip().lower() == "y"

    print("\nSEAT AVAILABILITY")
    for route in routes:
        if only_available and route["available_seats"] == 0:
            continue
        print(f"{route['route_id']} | {route['departure_city']} -> "
              f"{route['destination_city']} | "
              f"{route['available_seats']}/{route['total_seats']} | "
              f"{seat_status(route)}")


# STEP 10: REPORT (Feature 9)
def generate_report():
    confirmed_count = 0
    cancelled_count = 0
    reserved_seats = 0
    confirmed_revenue = 0
    fully_booked = 0

    for b in bookings:
        if b["status"] == "Confirmed":
            confirmed_count += 1
        else:
            cancelled_count += 1

    print("\nBOOKING REPORT")
    print("Confirmed bookings grouped by route:")


    for route in routes:
        route_seats = 0
        route_revenue = 0
        for b in bookings:
            if b["route_id"] == route["route_id"] and b["status"] == "Confirmed":
                route_seats += b["seats"]
                route_revenue += b["total_fare"]
        reserved_seats += route_seats
        confirmed_revenue += route_revenue
        if route["available_seats"] == 0:
            fully_booked += 1
        print(f"  {route['route_id']}: {route_seats} seats, Rs. {route_revenue:,}")

    print("-" * 32)
    print(f"Total bookings created: {len(bookings)}")
    print(f"Confirmed bookings: {confirmed_count}")
    print(f"Cancelled bookings: {cancelled_count}")
    print(f"Seats currently reserved: {reserved_seats}")
    print(f"Confirmed revenue: Rs. {confirmed_revenue:,}")
    print(f"Fully booked routes: {fully_booked}")


# STEP 11: PROGRAM LOOP
def main():
    while True:
        show_menu()
        choice = input("Enter your choice: ").strip()

        if not choice.isdigit():
            print("Invalid input. Please enter a number from 1 to 8.")
            continue

        choice = int(choice)
        if choice == 1:
            view_routes()
        elif choice == 2:
            search_routes()
        elif choice == 3:
            book_ticket()
        elif choice == 4:
            view_bookings()
        elif choice == 5:
            cancel_booking()
        elif choice == 6:
            view_availability()
        elif choice == 7:
            generate_report()
        elif choice == 8:
            print("Thank you for using Smart Bus Reservation System. Goodbye!")
            break
        else:
            print("Invalid choice. Please enter a number from 1 to 8.")


if __name__ == "__main__":
    main()